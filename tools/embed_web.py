#!/usr/bin/env python3
"""Deterministically embed Chaos's self-contained LAN console (no CDN)."""
import argparse
import gzip
import io
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WEB = ROOT / 'supervisor/network/web'


def rendered_html(web=WEB):
    source = (web / 'index.html').read_text(encoding='utf-8')
    script = (web / 'console.js').read_text(encoding='utf-8')
    marker = '<script src="console.js"></script>'
    if source.count(marker) != 1 or '</script' in script.lower():
        raise ValueError('expected one console.js marker and safe inline script')
    return source.replace(marker, '<script>\n' + script + '\n</script>').encode('utf-8')


def generated_header(web=WEB):
    data = rendered_html(web)
    output = io.BytesIO()
    # GzipFile fixes both timestamp and OS header across Python/platform versions.
    with gzip.GzipFile(fileobj=output, mode='wb', filename='', mtime=0, compresslevel=9) as file:
        file.write(data)
    packed = output.getvalue()
    lines = ['/* Generated by tools/embed_web.py; edit index.html / console.js. */',
             '#ifndef CHAOS_WEB_INDEX_H', '#define CHAOS_WEB_INDEX_H',
             f'#define WEB_INDEX_SIZE {len(packed)}u',
             'static const unsigned char web_index[WEB_INDEX_SIZE] = {']
    lines += ['    ' + ','.join(f'0x{n:02x}' for n in packed[i:i+16]) + ','
              for i in range(0, len(packed), 16)]
    return '\n'.join(lines + ['};', '#endif', ''])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--web-dir', type=Path, default=WEB, help='web source and generated header directory')
    parser.add_argument('--check', action='store_true', help='fail if the embedded header is stale')
    args = parser.parse_args()
    target = args.web_dir / 'web_index.h'
    generated = generated_header(args.web_dir)
    if args.check:
        if not target.exists() or target.read_text(encoding='ascii') != generated:
            parser.exit(1, 'web_index.h is stale; run python3 tools/embed_web.py\n')
    else:
        target.write_text(generated, encoding='ascii')
    print(f'web_index.h: {len(rendered_html(args.web_dir))} HTML bytes; deterministic gzip verified')


if __name__ == '__main__':
    main()
